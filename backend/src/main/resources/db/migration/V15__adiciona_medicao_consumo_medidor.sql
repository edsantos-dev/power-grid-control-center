CREATE TABLE medicao_consumo_medidor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_id BIGINT NOT NULL,
    inicio_periodo TIMESTAMP WITH TIME ZONE NOT NULL,
    fim_periodo TIMESTAMP WITH TIME ZONE NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    consumo_kwh NUMERIC(19, 6) NOT NULL,
    consumidor_id BIGINT NOT NULL,
    transformador_id BIGINT NOT NULL,
    alimentador_id BIGINT NOT NULL,
    subestacao_id BIGINT NOT NULL,
    CONSTRAINT fk_consumo_medidor_fonte FOREIGN KEY (fonte_id) REFERENCES fonte_medicao (id),
    CONSTRAINT fk_consumo_medidor_consumidor FOREIGN KEY (consumidor_id) REFERENCES consumidor (id),
    CONSTRAINT fk_consumo_medidor_transformador FOREIGN KEY (transformador_id) REFERENCES transformador (id),
    CONSTRAINT fk_consumo_medidor_alimentador FOREIGN KEY (alimentador_id) REFERENCES alimentador (id),
    CONSTRAINT fk_consumo_medidor_subestacao FOREIGN KEY (subestacao_id) REFERENCES subestacao (id),
    CONSTRAINT uq_consumo_medidor_fonte_periodo UNIQUE (fonte_id, inicio_periodo, fim_periodo),
    CONSTRAINT ck_consumo_medidor_periodo CHECK (inicio_periodo < fim_periodo),
    CONSTRAINT ck_consumo_medidor_valor CHECK (
        consumo_kwh >= 0
        AND CAST(consumo_kwh AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    )
);
