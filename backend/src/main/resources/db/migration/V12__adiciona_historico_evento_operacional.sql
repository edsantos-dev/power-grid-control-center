UPDATE evento_operacional
SET situacao = UPPER(TRIM(situacao))
WHERE situacao IS NOT NULL
    AND UPPER(TRIM(situacao)) IN ('ABERTO', 'EM_ANDAMENTO', 'CONCLUIDO')
    AND situacao <> UPPER(TRIM(situacao));

CREATE TABLE historico_evento_operacional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    situacao_anterior VARCHAR(32) NOT NULL,
    situacao_nova VARCHAR(32) NOT NULL,
    alterado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    comentario VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_historico_evento FOREIGN KEY (evento_id) REFERENCES evento_operacional (id),
    CONSTRAINT fk_historico_evento_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_historico_evento_transicao CHECK (
        (situacao_anterior = 'ABERTO' AND situacao_nova = 'EM_ANDAMENTO')
        OR (situacao_anterior = 'EM_ANDAMENTO' AND situacao_nova = 'CONCLUIDO')
    )
);

CREATE INDEX idx_historico_evento_instante
    ON historico_evento_operacional (evento_id, alterado_em, id);
