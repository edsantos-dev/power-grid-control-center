CREATE TABLE medicao_transformador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_id BIGINT NOT NULL,
    medido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    potencia_aparente_mva NUMERIC(19, 6) NOT NULL,
    capacidade_referencia_mva NUMERIC(19, 6) NOT NULL,
    CONSTRAINT fk_medicao_transformador_fonte FOREIGN KEY (fonte_id) REFERENCES fonte_medicao (id),
    CONSTRAINT ck_medicao_transformador_potencia CHECK (
        potencia_aparente_mva >= 0 AND CAST(potencia_aparente_mva AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_medicao_transformador_capacidade CHECK (
        capacidade_referencia_mva > 0 AND CAST(capacidade_referencia_mva AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    )
);
CREATE INDEX idx_medicao_transformador_fonte_instante ON medicao_transformador (fonte_id, medido_em);
