ALTER TABLE evento_operacional
    ADD COLUMN versao_designacao INTEGER DEFAULT 0 NOT NULL;

ALTER TABLE evento_operacional
    ADD CONSTRAINT ck_evento_versao_designacao CHECK (versao_designacao >= 0);

CREATE TABLE historico_designacao_equipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_operacional_id BIGINT NOT NULL,
    equipe_anterior_id BIGINT,
    equipe_nova_id BIGINT,
    usuario_id BIGINT NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    comentario VARCHAR(1000) NOT NULL,
    versao_designacao INTEGER NOT NULL,
    CONSTRAINT fk_designacao_evento FOREIGN KEY (evento_operacional_id) REFERENCES evento_operacional (id),
    CONSTRAINT fk_designacao_equipe_anterior FOREIGN KEY (equipe_anterior_id) REFERENCES equipe_manutencao (id),
    CONSTRAINT fk_designacao_equipe_nova FOREIGN KEY (equipe_nova_id) REFERENCES equipe_manutencao (id),
    CONSTRAINT fk_designacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_historico_designacao_versao CHECK (versao_designacao >= 0),
    CONSTRAINT uq_designacao_evento_versao UNIQUE (evento_operacional_id, versao_designacao)
);

CREATE INDEX idx_designacao_evento_instante
    ON historico_designacao_equipe (evento_operacional_id, registrado_em, id);
