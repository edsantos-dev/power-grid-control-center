CREATE TABLE alerta_tensao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id BIGINT NOT NULL,
    medicao_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    tensao_medida_kv NUMERIC(19, 6) NOT NULL,
    tensao_referencia_kv NUMERIC(19, 6) NOT NULL,
    limite_inferior_kv NUMERIC(22, 8) NOT NULL,
    limite_superior_kv NUMERIC(22, 8) NOT NULL,
    status VARCHAR(20) NOT NULL,
    gerado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    reconhecido_em TIMESTAMP WITH TIME ZONE,
    reconhecido_por_usuario_id BIGINT,
    CONSTRAINT fk_tensao_ativo FOREIGN KEY (ativo_id) REFERENCES ativo_rede (id),
    CONSTRAINT fk_tensao_medicao FOREIGN KEY (medicao_id) REFERENCES medicao_linha (id),
    CONSTRAINT uq_tensao_medicao UNIQUE (medicao_id),
    CONSTRAINT fk_tensao_usuario FOREIGN KEY (reconhecido_por_usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_tensao_tipo CHECK (tipo IN ('SUBTENSAO', 'SOBRETENSAO')),
    CONSTRAINT ck_tensao_medida CHECK (
        tensao_medida_kv >= 0 AND CAST(tensao_medida_kv AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_tensao_referencia CHECK (
        tensao_referencia_kv > 0 AND CAST(tensao_referencia_kv AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_tensao_limite_inferior CHECK (
        limite_inferior_kv > 0 AND CAST(limite_inferior_kv AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_tensao_limite_superior CHECK (
        limite_superior_kv > 0 AND CAST(limite_superior_kv AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_tensao_ciclo CHECK (
        (status = 'ATIVO' AND reconhecido_em IS NULL AND reconhecido_por_usuario_id IS NULL)
        OR (status = 'RECONHECIDO' AND reconhecido_em IS NOT NULL AND reconhecido_por_usuario_id IS NOT NULL)
    )
);

CREATE INDEX idx_tensao_ativo_gerado ON alerta_tensao (ativo_id, gerado_em);
CREATE INDEX idx_tensao_status_gerado ON alerta_tensao (status, gerado_em);
