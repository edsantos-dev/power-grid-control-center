ALTER TABLE alimentador ADD COLUMN percentual_perda_tecnica NUMERIC(9, 6);
ALTER TABLE alimentador ADD CONSTRAINT ck_alimentador_percentual_perda
    CHECK (percentual_perda_tecnica >= 0 AND percentual_perda_tecnica < 100
        AND CAST(percentual_perda_tecnica AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity'));

CREATE TABLE medicao_energia_alimentador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_id BIGINT NOT NULL,
    inicio_periodo TIMESTAMP WITH TIME ZONE NOT NULL,
    fim_periodo TIMESTAMP WITH TIME ZONE NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    energia_injetada_mwh NUMERIC(19, 6) NOT NULL,
    percentual_perda_referencia NUMERIC(9, 6) NOT NULL,
    CONSTRAINT fk_medicao_energia_fonte FOREIGN KEY (fonte_id) REFERENCES fonte_medicao (id),
    CONSTRAINT uq_medicao_energia_fonte_periodo UNIQUE (fonte_id, inicio_periodo, fim_periodo),
    CONSTRAINT ck_medicao_energia_periodo CHECK (inicio_periodo < fim_periodo),
    CONSTRAINT ck_medicao_energia_injetada CHECK (
        energia_injetada_mwh >= 0
        AND CAST(energia_injetada_mwh AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_medicao_energia_percentual CHECK (
        percentual_perda_referencia >= 0 AND percentual_perda_referencia < 100
        AND CAST(percentual_perda_referencia AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    )
);
