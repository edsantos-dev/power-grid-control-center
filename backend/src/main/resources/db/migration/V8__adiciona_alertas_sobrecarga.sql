CREATE TABLE alerta_sobrecarga (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id BIGINT NOT NULL,
    medicao_id BIGINT NOT NULL,
    carga_percentual NUMERIC(27, 6) NOT NULL,
    limiar_percentual NUMERIC(19, 6) NOT NULL,
    status VARCHAR(20) NOT NULL,
    gerado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    reconhecido_em TIMESTAMP WITH TIME ZONE,
    reconhecido_por_usuario_id BIGINT,
    CONSTRAINT fk_sobrecarga_ativo FOREIGN KEY (ativo_id) REFERENCES ativo_rede (id),
    CONSTRAINT fk_sobrecarga_medicao FOREIGN KEY (medicao_id) REFERENCES medicao_transformador (id),
    CONSTRAINT uq_sobrecarga_medicao UNIQUE (medicao_id),
    CONSTRAINT fk_sobrecarga_usuario FOREIGN KEY (reconhecido_por_usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_sobrecarga_limiar CHECK (
        limiar_percentual > 0 AND CAST(limiar_percentual AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_sobrecarga_carga_finita CHECK (
        CAST(carga_percentual AS VARCHAR) NOT IN ('NaN', 'Infinity', '-Infinity')
    ),
    CONSTRAINT ck_sobrecarga_ciclo CHECK (
        (status = 'ATIVO' AND reconhecido_em IS NULL AND reconhecido_por_usuario_id IS NULL)
        OR (status = 'RECONHECIDO' AND reconhecido_em IS NOT NULL AND reconhecido_por_usuario_id IS NOT NULL)
    )
);

CREATE INDEX idx_sobrecarga_ativo_gerado ON alerta_sobrecarga (ativo_id, gerado_em);
CREATE INDEX idx_sobrecarga_status_gerado ON alerta_sobrecarga (status, gerado_em);
