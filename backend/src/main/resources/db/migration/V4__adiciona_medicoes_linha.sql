CREATE TABLE fonte_medicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador VARCHAR(128) NOT NULL,
    linha_id BIGINT NOT NULL,
    origem VARCHAR(16) NOT NULL,
    CONSTRAINT uq_fonte_identificador UNIQUE (identificador),
    CONSTRAINT fk_fonte_linha FOREIGN KEY (linha_id) REFERENCES linha_transmissao (id),
    CONSTRAINT ck_fonte_origem CHECK (origem IN ('REAL', 'SIMULADA'))
);

CREATE TABLE medicao_linha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_id BIGINT NOT NULL,
    medido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    tensao_kv NUMERIC(19, 6),
    corrente_a NUMERIC(19, 6),
    CONSTRAINT fk_medicao_fonte FOREIGN KEY (fonte_id) REFERENCES fonte_medicao (id),
    CONSTRAINT ck_medicao_grandeza CHECK (tensao_kv IS NOT NULL OR corrente_a IS NOT NULL),
    CONSTRAINT ck_medicao_tensao CHECK (tensao_kv >= 0 AND CAST(tensao_kv AS VARCHAR) <> 'NaN'),
    CONSTRAINT ck_medicao_corrente CHECK (corrente_a >= 0 AND CAST(corrente_a AS VARCHAR) <> 'NaN')
);

CREATE INDEX idx_medicao_fonte_instante ON medicao_linha (fonte_id, medido_em);
