ALTER TABLE fonte_medicao ADD COLUMN monitorada_desde TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE fonte_medicao ADD COLUMN ultima_comunicacao_em TIMESTAMP WITH TIME ZONE;

UPDATE fonte_medicao f
SET ultima_comunicacao_em = (
    SELECT MAX(leituras.recebido_em)
    FROM (
        SELECT fonte_id, recebido_em FROM medicao_linha
        UNION ALL
        SELECT fonte_id, recebido_em FROM medicao_transformador
    ) leituras
    WHERE leituras.fonte_id = f.id
);

ALTER TABLE fonte_medicao ALTER COLUMN monitorada_desde SET NOT NULL;

CREATE TABLE alerta_comunicacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte_id BIGINT NOT NULL,
    ativo_id BIGINT NOT NULL,
    monitorada_desde TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima_comunicacao_em TIMESTAMP WITH TIME ZONE,
    tolerancia_segundos INTEGER NOT NULL,
    detectado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    restabelecido_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_comunicacao_fonte FOREIGN KEY (fonte_id) REFERENCES fonte_medicao (id),
    CONSTRAINT fk_comunicacao_ativo FOREIGN KEY (ativo_id) REFERENCES ativo_rede (id),
    CONSTRAINT ck_comunicacao_tolerancia CHECK (tolerancia_segundos > 0),
    CONSTRAINT ck_comunicacao_ciclo CHECK (
        (status = 'ATIVO' AND restabelecido_em IS NULL)
        OR (status = 'RESTABELECIDO' AND restabelecido_em IS NOT NULL)
    )
);

CREATE INDEX idx_comunicacao_fonte_status ON alerta_comunicacao (fonte_id, status);
CREATE INDEX idx_comunicacao_detectado ON alerta_comunicacao (detectado_em, id);
