CREATE TABLE ativo_rede (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    estado_operacional VARCHAR(20) NOT NULL,
    data_instalacao DATE,
    CONSTRAINT ck_ativo_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ativo_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ativo_estado CHECK (
        estado_operacional IN ('OPERACIONAL', 'FALHA', 'MANUTENCAO')
    )
);

CREATE TABLE subestacao (
    id BIGINT PRIMARY KEY,
    tensao_nominal_kv NUMERIC(19, 6),
    capacidade_mva NUMERIC(19, 6),
    CONSTRAINT fk_subestacao_ativo FOREIGN KEY (id) REFERENCES ativo_rede (id)
);

CREATE TABLE alimentador (
    id BIGINT PRIMARY KEY,
    tensao_nominal_kv NUMERIC(19, 6),
    subestacao_id BIGINT NOT NULL,
    CONSTRAINT fk_alimentador_ativo FOREIGN KEY (id) REFERENCES ativo_rede (id),
    CONSTRAINT fk_alimentador_subestacao FOREIGN KEY (subestacao_id) REFERENCES subestacao (id)
);

CREATE TABLE transformador (
    id BIGINT PRIMARY KEY,
    capacidade_mva NUMERIC(19, 6) NOT NULL,
    alimentador_id BIGINT NOT NULL,
    CONSTRAINT fk_transformador_ativo FOREIGN KEY (id) REFERENCES ativo_rede (id),
    CONSTRAINT fk_transformador_alimentador FOREIGN KEY (alimentador_id) REFERENCES alimentador (id),
    CONSTRAINT ck_transformador_capacidade CHECK (
        capacidade_mva > 0 AND CAST(capacidade_mva AS VARCHAR) <> 'NaN'
    )
);

CREATE TABLE linha_transmissao (
    id BIGINT PRIMARY KEY,
    extensao_km NUMERIC(19, 6),
    tensao_operacao_kv NUMERIC(19, 6),
    CONSTRAINT fk_linha_ativo FOREIGN KEY (id) REFERENCES ativo_rede (id)
);

CREATE TABLE usina_geradora (
    id BIGINT PRIMARY KEY,
    tipo_geracao VARCHAR(100),
    capacidade_maxima_mw NUMERIC(19, 6),
    CONSTRAINT fk_usina_ativo FOREIGN KEY (id) REFERENCES ativo_rede (id)
);

CREATE TABLE consumidor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_razao_social VARCHAR(255),
    tipo_pessoa VARCHAR(2) NOT NULL,
    documento VARCHAR(32) NOT NULL,
    endereco_correspondencia TEXT,
    CONSTRAINT uq_consumidor_documento UNIQUE (documento),
    CONSTRAINT ck_consumidor_tipo_pessoa CHECK (tipo_pessoa IN ('PF', 'PJ'))
);

CREATE TABLE medidor_inteligente (
    id BIGINT PRIMARY KEY,
    numero_serie VARCHAR(128) NOT NULL,
    endereco_fornecimento TEXT,
    consumidor_id BIGINT,
    transformador_id BIGINT,
    CONSTRAINT uq_medidor_numero_serie UNIQUE (numero_serie),
    CONSTRAINT fk_medidor_ativo FOREIGN KEY (id) REFERENCES ativo_rede (id),
    CONSTRAINT fk_medidor_consumidor FOREIGN KEY (consumidor_id) REFERENCES consumidor (id),
    CONSTRAINT fk_medidor_transformador FOREIGN KEY (transformador_id) REFERENCES transformador (id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    matricula VARCHAR(64) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255),
    perfil VARCHAR(32) NOT NULL,
    cargo_profissional VARCHAR(255),
    CONSTRAINT uq_usuario_matricula UNIQUE (matricula),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (
        perfil IN ('OPERADOR', 'GERENTE_OPERACOES', 'TECNICO_MANUTENCAO')
    )
);

CREATE TABLE equipe_manutencao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    situacao VARCHAR(32),
    responsabilidades TEXT,
    especialidades TEXT
);

CREATE TABLE vinculo_equipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipe_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    inicio_vigencia TIMESTAMP WITH TIME ZONE,
    fim_vigencia TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_vinculo_equipe FOREIGN KEY (equipe_id) REFERENCES equipe_manutencao (id),
    CONSTRAINT fk_vinculo_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_vinculo_vigencia CHECK (fim_vigencia >= inicio_vigencia)
);

CREATE TABLE evento_operacional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ativo_id BIGINT NOT NULL,
    categoria VARCHAR(32) NOT NULL,
    criticidade VARCHAR(32),
    descricao TEXT,
    situacao VARCHAR(32),
    registrador_usuario_id BIGINT NOT NULL,
    responsavel_usuario_id BIGINT NOT NULL,
    equipe_designada_id BIGINT,
    inicio_previsto TIMESTAMP WITH TIME ZONE,
    inicio_efetivo TIMESTAMP WITH TIME ZONE,
    termino_previsto TIMESTAMP WITH TIME ZONE,
    termino_efetivo TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_evento_ativo FOREIGN KEY (ativo_id) REFERENCES ativo_rede (id),
    CONSTRAINT fk_evento_registrador FOREIGN KEY (registrador_usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_evento_responsavel FOREIGN KEY (responsavel_usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_evento_equipe FOREIGN KEY (equipe_designada_id) REFERENCES equipe_manutencao (id),
    CONSTRAINT ck_evento_categoria CHECK (
        categoria IN (
            'MANOBRA', 'DESLIGAMENTO_PROGRAMADO', 'INTERRUPCAO_FORNECIMENTO',
            'SOBRECARGA', 'FALHA_EQUIPAMENTO', 'MANUTENCAO'
        )
    ),
    CONSTRAINT ck_evento_periodo_previsto CHECK (termino_previsto >= inicio_previsto),
    CONSTRAINT ck_evento_periodo_efetivo CHECK (termino_efetivo >= inicio_efetivo)
);

CREATE TABLE alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(128),
    criticidade VARCHAR(32),
    gerado_em TIMESTAMP WITH TIME ZONE,
    situacao VARCHAR(32),
    escopo VARCHAR(20) NOT NULL,
    ativo_id BIGINT,
    CONSTRAINT fk_alerta_ativo FOREIGN KEY (ativo_id) REFERENCES ativo_rede (id),
    CONSTRAINT ck_alerta_escopo CHECK (
        (escopo = 'ATIVO' AND ativo_id IS NOT NULL)
        OR (escopo = 'REDE_MONITORADA' AND ativo_id IS NULL)
    )
);
