CREATE TABLE historico_alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    situacao_anterior VARCHAR(32) NOT NULL,
    situacao_nova VARCHAR(32) NOT NULL,
    alterado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    comentario VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_historico_alerta FOREIGN KEY (alerta_id) REFERENCES alerta (id),
    CONSTRAINT fk_historico_alerta_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_historico_alerta_transicao CHECK (
        (situacao_anterior = 'ABERTO' AND situacao_nova = 'RECONHECIDO')
        OR (situacao_anterior = 'RECONHECIDO' AND situacao_nova = 'RESOLVIDO')
    ),
    CONSTRAINT uq_historico_alerta_destino UNIQUE (alerta_id, situacao_nova)
);

CREATE INDEX idx_historico_alerta_instante
    ON historico_alerta (alerta_id, alterado_em, id);
